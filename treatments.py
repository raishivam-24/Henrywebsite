def featured_treatments():
    out = []
    for t in TREATMENTS.values():
        if not t.get('featured'):
            continue
        item = dict(t)
        hi = TREATMENTS_HI.get(t['slug'], {})
        item['hi_title'] = hi.get('title', t['title'])
        item['hi_summary'] = hi.get('summary', t['summary'])
        item['hi_sessions'] = hi.get('sessions', t['sessions'])
        out.append(item)
    return out


